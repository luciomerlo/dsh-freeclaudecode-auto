/**
 * Build the browser artifact without any third-party toolchain.
 *
 * The Client module loader expects a classic script that registers a lazy
 * factory under the package name and receives `react` from the browser module
 * table. The source exports `createPlugin(React)` as ordinary ESM; this script
 * removes that one export keyword and wraps the body in the loader call, so the
 * build is deterministic and `npm run build` works on a fresh clone.
 *
 * @module dsh-freeclaudecode-auto/scripts/build
 */

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))

/** Read and validate the package manifest. */
async function readManifest() {
  const manifest = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
  if (typeof manifest.name !== 'string' || manifest.name === '') {
    throw new Error('build: package.json needs a non-empty name')
  }
  if (typeof manifest.version !== 'string' || manifest.version === '') {
    throw new Error('build: package.json needs a non-empty version')
  }
  return manifest
}

/** Validate every locale document before it ships. */
async function checkLocales() {
  for (const locale of ['en']) {
    const text = await readFile(join(root, 'locale', `${locale}.json`), 'utf8')
    const parsed = JSON.parse(text)
    if (typeof parsed?.meta?.title !== 'string' || typeof parsed?.meta?.description !== 'string') {
      throw new Error(`build: locale/${locale}.json needs meta.title and meta.description`)
    }
  }
}

/** Strip the single `export` keyword from the Client source. */
function toFactoryBody(source) {
  const matches = source.match(/^export /gmu) ?? []
  if (matches.length !== 1) {
    throw new Error(`build: src/client/index.js must have exactly one top-level export, found ${String(matches.length)}`)
  }
  return source.replace(/^export function createPlugin/mu, 'function createPlugin')
}

/** Generate `client.js` from the Client source. */
async function buildClient(manifest) {
  const source = await readFile(join(root, 'src', 'client', 'index.js'), 'utf8')
  const body = toFactoryBody(source)
  const artifact = `/* Generated by scripts/build.mjs from src/client/index.js — do not edit directly. */\n`
    + `window.__ModuleLoader__.load({\n`
    + `  id: ${JSON.stringify(manifest.name)},\n`
    + `  factory(require) {\n`
    + `    const React = require('react');\n`
    + `${body}\n`
    + `    return createPlugin(React);\n`
    + `  },\n`
    + `});\n`
  await writeFile(join(root, 'client.js'), artifact, 'utf8')
  return artifact.length
}

/** Run the build. */
async function main() {
  const manifest = await readManifest()
  await checkLocales()
  const bytes = await buildClient(manifest)
  process.stdout.write(`build: client.js written (${String(bytes)} bytes)\n`)
  process.stdout.write(`build: ${manifest.name}@${manifest.version} is ready to install\n`)
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
})
